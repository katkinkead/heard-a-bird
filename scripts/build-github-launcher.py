#!/usr/bin/env python3
"""Build/check the self-contained Mac launcher from its tested source module."""
import argparse
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from songsketch.github_launcher import download_command, download_zip, download_template

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
outputs = {ROOT / "scripts/github-install.command": download_command(), ROOT / "scripts/github-install.zip": download_zip()}
outputs[ROOT / "guide/assets/installer-source.js"] = ("/* Generated by scripts/build-github-launcher.py; no private setup values. */\nwindow.SONGSKETCH_INSTALLER_TEMPLATE = " + json.dumps(download_template().decode()) + ";\n").encode()
for path, content in outputs.items():
    if args.check:
        if not path.is_file() or path.read_bytes() != content:
            raise SystemExit("Launcher is stale: run python3 scripts/build-github-launcher.py")
    else:
        path.write_bytes(content)
        path.chmod(0o755 if path.suffix == ".command" else 0o644)
print("Self-contained GitHub launcher matches its source." if args.check else "Built the GitHub launcher and executable-preserving ZIP.")
